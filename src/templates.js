export function subFor(type, years) {
  if (type === 'yearly') return `${years} ${Number(years) === 1 ? 'година' : 'години'} без теб`
  return TYPES.find((t) => t.id === type)?.sub ?? ''
}

const g = (f, m, w) => (f.gender === 'f' ? w : m)

